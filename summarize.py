#!/usr/bin/env python3
"""Build results/summary.md and results/summary.json from the raw runs.

Attribution rules (see docs/04-testing.md):
  * cases the fix must not change: upstream and fixed LLVM must fail identically, field by field
  * cases the fix changes: identical failures (outside the replaced aggregate) to the twin case
  * code: only functions with an odd-size byval aggregate may change; no new verifier failures
Anything that does not satisfy its rule is listed as UNEXPLAINED.
"""
import collections, glob, json, os, re, sys

ROOT = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(ROOT, "harness"))
import config
RUNS = config.RUNS
S = {}          # summary.json
md = []         # summary.md
unexplained = []

import sweepdata as SD
load, mismatches = SD.load, SD.mismatches

def h(t): md.append(t)

# ------------------------------------------------------------------ repro + lit + check-llvm
h("# Results\n")
h("Generated by `summarize.py` from `runs/`. Methodology: [docs/04-testing.md](../docs/04-testing.md).\n")
h("## Reproduction of esp-rs/rust#278\n")
for step in ("01_symptom", "02_rustc_abi", "03_llvm_lowering", "04_gcc_reference"):
    p = os.path.join(ROOT, "results", "repro", step + ".txt")
    h(f"* [{step}](repro/{step}.txt)" + ("" if os.path.exists(p) else " - MISSING"))
sym = os.path.join(ROOT, "results", "repro", "01_symptom.txt")
if os.path.exists(sym):
    h("\n```\n" + "\n".join(l for l in open(sym, encoding="utf-8").read().splitlines() if re.search(r"arguments arrive wrong", l)) + "\n```\n")

lit = load(os.path.join(ROOT, "results", "llvm-lit.json"))
h("## LLVM lit\n")
if lit:
    S["lit"] = {"new_test_upstream_failed": lit["new_test_with_upstream_source"]["failed"], "new_test_fixed_failed": lit["new_test_with_fix"]["failed"],
                "xtensa_summary": lit["all_xtensa_with_fix"]["summary"], "ok": lit["ok"]}
    h(f"* new test `calling-conv-stack-align.ll` with upstream source: **{'FAIL' if lit['new_test_with_upstream_source']['failed'] else 'pass (unexpected)'}**")
    h(f"* new test with the fix: **{'PASS' if not lit['new_test_with_fix']['failed'] else 'FAIL'}**")
    h(f"* all Xtensa tests with the fix: {'; '.join(lit['all_xtensa_with_fix']['summary'])}\n")
    if not lit["ok"]:
        unexplained.append("llvm lit stage not ok")
else:
    h("* not run\n"); unexplained.append("llvm lit stage missing")
chk = load(os.path.join(ROOT, "results", "check-llvm.json"))
h("## check-llvm (complete LLVM test suite, X86 + Xtensa build)\n")
if chk:
    S["check_llvm"] = {"total": chk["fixed"]["total"], "failed": chk["fixed"]["failed"], "new_failures": chk["new_failures"], "summary": chk["fixed"]["summary"]}
    h(f"* discovered tests: {chk['fixed']['total']}; " + "; ".join(chk["fixed"]["summary"]))
    h(f"* failures with the fix: {len(chk['fixed']['failed'])}; of these also failing with upstream source: "
      f"{len(chk['fixed']['failed']) - len(chk['new_failures'])}; **new: {len(chk['new_failures'])}**\n")
    for t in chk["new_failures"]:
        unexplained.append(f"check-llvm new failure {t}")
else:
    h("* not run\n"); unexplained.append("check-llvm missing")

# ------------------------------------------------------------------ Rust-level stage
h("## Rust caller/callee against GCC (stage `rust`)\n")
rows = collections.defaultdict(lambda: collections.Counter())
asm_note = collections.defaultdict(list)
for p in glob.glob(os.path.join(RUNS, "matrix", "*.json")):
    r = load(p) or {}
    g = os.path.basename(p).split("_")[0]
    c = rows[g]; c["runs"] += 1; c["finished"] += bool(r.get("done")); c["crashed"] += bool(r.get("exception"))
    c["checks"] += r.get("checks") or 0
    for path, cs, *_ in mismatches(p[:-5]):
        c[f"fail:{path}"] += 1
    if "asm_identical_to_compare_llc" in r:
        c["asm identical"] += bool(r["asm_identical_to_compare_llc"])
    c["verifier_bad"] += len(r.get("verifier_bad_functions") or [])
desc = {"R1": "fixed rustc + fixed LLVM", "R2": "fixed rustc + A+B LLVM (vs fixed)", "R3": "upstream rustc + upstream LLVM, no odd structs",
        "R4": "upstream rustc + fixed LLVM (vs upstream)", "R5": "fixed rustc + alternative A", "R6": "fixed rustc + upstream LLVM, no odd structs"}
h("| group | configuration | runs | finished | crashed | checks | failures by path | verifier bad fns |")
h("|---|---|---|---|---|---|---|---|")
for g in sorted(rows):
    c = rows[g]
    fails = ", ".join(f"{k[5:]}={v}" for k, v in sorted(c.items()) if k.startswith("fail:")) or "0"
    h(f"| {g} | {desc.get(g, '')} | {c['runs']} | {c['finished']} | {c['crashed']} | {c['checks']} | {fails} | {c['verifier_bad']} |")
S["rust_matrix"] = {g: dict(c) for g, c in rows.items()}
r1 = rows.get("R1", {})
plain_fail = sum(v for k, v in r1.items() if k in ("fail:gcc->rust", "fail:rust->gcc", "fail:gcc->gcc(control)"))
h(f"\nR1 non-vararg paths: {plain_fail} failures; vararg `rust->gcc` failures equal the GCC control's: "
  f"{r1.get('fail:va:rust->gcc', 0)} vs {r1.get('fail:va:gcc->gcc(control)', 0)} (GCC self-inconsistency, docs/05 #5).")
if plain_fail:
    unexplained.append("R1 plain-path failures")
if r1.get("fail:va:rust->gcc", 0) != r1.get("fail:va:gcc->gcc(control)", 0):
    unexplained.append("R1 va rust->gcc differs from control")
tw = collections.Counter()
twin_runs = sorted(glob.glob(os.path.join(RUNS, "twin", "*.json")))
for p in twin_runs:
    r = load(p) or {}
    tw["runs"] += 1; tw["finished"] += bool(r.get("done")); tw["checks"] += r.get("checks") or 0
h(f"\nTwin runs (odd struct vs S8 twin, rustc O0/O3, llc O0/O2): {tw['runs']} runs, {tw['finished']} finished, {tw['checks']} checks - details in `harness/analyze_twin.py`.\n")
S["rust_twin"] = dict(tw)

# ------------------------------------------------------------------ IR sweeps
def sweep_summary(title, dirname, cases, local_to_global, odd_of, twin_of, field_skip, cmp_dirs, known_error=None):
    """cases: list; local_to_global(run_dir, result) -> list mapping; odd_of(case)->bool; twin_of(gi)->gi or None"""
    h(f"## {title}\n")
    groups = collections.defaultdict(list)
    for p in glob.glob(os.path.join(RUNS, dirname, "*.json")):
        name = os.path.basename(p)[:-5]
        m = re.match(r"(B|base)_(\w+?)_(O\d)(?:_(\d+))?(_irva)?$", name)
        if not m:
            continue
        groups[(m.group(1), m.group(2), m.group(3), bool(m.group(5)))].append(p)
    table, block = [], {}
    for key in sorted(groups):
        v, chip, opt, irva = key
        tot = collections.Counter(); fails = collections.defaultdict(set)
        for p in groups[key]:
            r = load(p) or {}
            tot["chunks"] += 1; tot["finished"] += bool(r.get("done")); tot["checks"] += r.get("checks") or 0
            if r.get("exception"): tot["crashed"] += 1
            if "error" in r:
                tot["known_error" if known_error and known_error in r["error"] else "error"] += 1
            m = local_to_global(p[:-5], r)
            for path, lc, field, got, exp in mismatches(p[:-5]):
                fails[m[lc]].add((path, field))
        block[key] = fails
        byp = collections.Counter(path for fs in fails.values() for path, _ in fs)
        table.append((key, tot, byp))
    h("| LLVM | config | opt | IR va_arg | chunks | finished | crashed | errors | checks | failing checks by path |")
    h("|---|---|---|---|---|---|---|---|---|---|")
    for (v, chip, opt, irva), tot, byp in table:
        err = f"{tot['error']}" + (f" (+{tot['known_error']} known)" if tot["known_error"] else "")
        h(f"| {'fixed' if v == 'B' else 'upstream'} | {chip} | {opt} | {'yes' if irva else 'no'} | {tot['chunks']} | {tot['finished']} | {tot['crashed']} | {err} | {tot['checks']} | "
          + (", ".join(f"{k}={n}" for k, n in sorted(byp.items())) or "0") + " |")
        if v == "B" and tot["error"]:
            unexplained.append(f"{title}: fixed {chip} {opt} has {tot['error']} errored chunks")
        if v == "B" and tot["finished"] + tot["known_error"] < tot["chunks"]:
            unexplained.append(f"{title}: fixed {chip} {opt} irva={irva}: only {tot['finished']}/{tot['chunks']} chunks finished")
    # twin attribution for the fixed LLVM
    res = {}
    for key, fails in block.items():
        if key[0] != "B":
            continue
        c = collections.Counter()
        for gi, fs in fails.items():
            if any(p == "c->c" for p, _ in fs):
                c["GCC self-inconsistent (excluded)"] += 1; continue
            if not odd_of(cases[gi]):
                c["unchanged case, failing (checked against upstream below)"] += 1; continue
            tj = twin_of(gi)
            skip = field_skip(cases[gi])
            a = {(p, f) for p, f in fs if not any(re.fullmatch(rf"{s}[a-z]*", f) for s in skip)}
            b = {(p, f) for p, f in fails.get(tj, set()) if not any(re.fullmatch(rf"{s}[a-z]*", f) for s in skip)} if tj is not None else None
            if b is None:
                c["odd case without twin"] += 1; unexplained.append(f"{title} {key}: case {gi} has no twin")
            elif a == b:
                c["odd case, identical to twin"] += 1
            else:
                c["odd case, DIFFERENT from twin"] += 1; unexplained.append(f"{title} {key}: case {gi} differs from twin {tj}")
        res[key] = dict(c)
    # upstream vs fixed on cases the fix must not change
    cmp = collections.Counter()
    # (chip, opt, irva) -> global case indices inside a list that ran identically with both LLVMs
    # in that same configuration
    covered = collections.defaultdict(set)
    for cmp_dir, list_of in cmp_dirs:
        pairs = collections.defaultdict(dict)
        for p in glob.glob(os.path.join(RUNS, cmp_dir, "*.json")):
            name = os.path.basename(p)[:-5]
            v, rest = name.split("_", 1)
            r = load(p) or {}
            pairs[rest][v] = (r.get("done"), r.get("checks") or 0, {(pa, lc, f) for pa, lc, f, *_ in mismatches(p[:-5])})
        for rest, d in sorted(pairs.items()):
            b, n = d.get("base"), d.get("B")
            lf = list_of(rest)
            if lf is None:        # a list no longer produced (e.g. from an earlier, superseded run)
                if os.environ.get("XT_DEBUG"): print("skip", cmp_dir, rest)
                continue
            cmp["lists"] += 1
            if b and n and b[0] and n[0] and b[2] == n[2] and b[1] == n[1]:
                cmp["identical"] += 1
                covered[SD.config_of(rest)] |= {int(x) for x in open(lf).read().split()}
            else:
                cmp["DIFFERENT or incomplete"] += 1; unexplained.append(f"{title}: base vs fixed differ on {cmp_dir}/{rest}")
            cmp["checks per side"] += n[1] if n else 0
            cmp["identical pre-existing failures"] += len(n[2]) if n and b and b[2] == n[2] else 0
    cmp_cov = {f"{c[0]} {c[1]}{' irva' if c[2] else ''}": len(v) for c, v in sorted(covered.items())}
    # every failing case the fix must not change has to be covered by such an identical comparison
    # in the same configuration
    for key, fails in block.items():
        if key[0] != "B":
            continue
        for gi, fs in fails.items():
            if any(p == "c->c" for p, _ in fs) or odd_of(cases[gi]):
                continue
            if gi in covered[key[1:]]:
                res[key]["unchanged case: same failure with upstream LLVM"] = res[key].get("unchanged case: same failure with upstream LLVM", 0) + 1
            else:
                res[key]["unchanged case: NOT covered by an upstream comparison"] = res[key].get("unchanged case: NOT covered by an upstream comparison", 0) + 1
                unexplained.append(f"{title} {key}: unchanged case {gi} fails but is not covered by an upstream comparison")
        res[key].pop("unchanged case, failing (checked against upstream below)", None)
    h("\nFixed LLVM, attribution of failing cases:\n")
    for key, c in sorted(res.items()):
        h(f"* {key[1]} {key[2]}{' IR va_arg' if key[3] else ''}: " + (", ".join(f"{k}: {v}" for k, v in sorted(c.items())) or "no failures"))
    h("\nUpstream vs fixed LLVM on cases the fix must not change (field-by-field):\n")
    h(f"* {dict(cmp)}\n")
    S[title] = {"table": [{"llvm": k[0], "chip": k[1], "opt": k[2], "irva": k[3], **dict(t), "fails_by_path": dict(bp)} for k, t, bp in table],
                "attribution": {str(k): v for k, v in res.items()}, "upstream_vs_fixed": dict(cmp), "covered_cases_per_config": cmp_cov}

# v1
import irsweep as W1
ALL1 = W1.cases()
IDX1 = {repr(c): i for i, c in enumerate(ALL1)}
def l2g_v1(run_dir, r):
    ci, cn = map(int, (r.get("chunk") or "0/1").split("/"))
    return collections.defaultdict(lambda: None, {i: ci + i * cn for i in range(len(ALL1))})
def odd1(c): return any(isinstance(x, tuple) and x[1] % 4 and x[1] > 4 for x in c[0])
def twin1(gi):
    params, var = ALL1[gi]
    for a in (1, 4):
        # only aggregates the fix changes (not a multiple of 4 and larger than 4) are rounded
        tp = [("S", (p[1] + 3) // 4 * 4, a) if isinstance(p, tuple) and p[1] % 4 and p[1] > 4 else p for p in params]
        if repr((tp, var)) in IDX1:
            return IDX1[repr((tp, var))]
def skip1(c): return [f"p{k}" for k, x in enumerate(c[0]) if isinstance(x, tuple) and x[1] % 4 and x[1] > 4]
def fixed_list(pattern):
    """list file of a comparison run named ..._<kind><k>[_irva], e.g. esp32s3_O2_even3"""
    def f(rest):
        m = re.search(r"_(even|small|u)(\d+)(?:_irva)?$", rest)
        return os.path.join(RUNS, pattern[m.group(1)].format(k=m.group(2))) if m else None
    return f
def confirm_list(key):
    """list file of a stage-`confirm` run; only lists the current results still produce count"""
    current = {rest: p for rest, *_, p in SD.confirm_lists(key)}
    return lambda rest: current.get(rest)
EVEN = fixed_list({"even": "evenlists/even_{k}.txt", "small": "evenlists/small_{k}.txt"})
sweep_summary("First IR sweep (1968 cases)", "sweep", ALL1, l2g_v1, odd1, twin1, skip1,
              [("even", EVEN), ("evensmall", EVEN), ("confirm_v1", confirm_list("v1"))])
sweep_summary("esp-clang sweep (1968 cases, C front end)", "csweep", ALL1, l2g_v1, odd1, twin1, skip1,
              [("ceven", EVEN), ("cevensmall", EVEN), ("confirm_clang", confirm_list("clang"))],
              known_error="Cannot scavenge register")
# v2
import irsweep2 as W2
ALL2 = W2.all_cases()
IDX2 = {json.dumps(c, sort_keys=True): i for i, c in enumerate(ALL2)}
def l2g_v2(run_dir, r):
    idx = load(os.path.join(run_dir, "case_index.json")) or []
    return collections.defaultdict(lambda: None, dict(enumerate(idx)))
def twin2(gi):
    return IDX2.get(json.dumps(W2.twin_case(ALL2[gi]), sort_keys=True))
def skip2(c): return [f"p{k}" for k, x in enumerate(c["params"]) if isinstance(x, str) and x.startswith("#") and W2.SHAPES[x[1:]].odd]
sweep_summary("Extended IR sweep (11714 cases)", "sweep2", ALL2, l2g_v2, W2.is_odd_case, twin2, skip2,
              [("sweep2cmp", fixed_list({"u": "v2lists/u_{k}.txt"})), ("confirm_v2", confirm_list("v2"))])

# ------------------------------------------------------------------ per-function code comparison
h("## Per-function code comparison (upstream vs fixed LLVM)\n")
def perfn_totals(dirname, cases_of):
    tot = collections.Counter()
    for p in glob.glob(os.path.join(RUNS, dirname, "*.json")):
        res = load(p) or {}
        for fn, e in res.items():
            tot["functions"] += 1
            odd = cases_of(p, fn)
            if not e["asm_identical"]:
                tot["asm differs"] += 1
                if odd is False:
                    tot["asm differs WITHOUT odd byval"] += 1; unexplained.append(f"{dirname}: {os.path.basename(p)} {fn} differs without odd byval")
                elif odd is None:
                    tot["asm differs, function not a generated case"] += 1; unexplained.append(f"{dirname}: {os.path.basename(p)} {fn} differs and is not a case function")
            if e["base_ok"] and not e["new_ok"]:
                tot["verifier: new failure with fix"] += 1; unexplained.append(f"{dirname}: {os.path.basename(p)} {fn} new verifier failure")
            if not e["base_ok"] and e["new_ok"]: tot["verifier: fixed by the fix"] += 1
            if not e["base_ok"] and not e["new_ok"]: tot["verifier: fails with both"] += 1
    return dict(tot)
def case_v1(p, fn):
    m = re.match(r"(?:ircallee|ircaller|irdyn)(\d+)$", fn)
    if not m: return None
    i = int(os.path.basename(p)[:-5].rsplit("_", 1)[1])
    return odd1(ALL1[i + int(m.group(1)) * 20])
def case_v2(p, fn):
    m = re.match(r"(?:ircallee|ircaller|irdyn)(\d+)$", fn)
    if not m: return None
    i = int(os.path.basename(p)[:-5].rsplit("_", 1)[1])
    idx = load(os.path.join(RUNS, "sweep2", f"B_esp32s3_O2_{i}", "case_index.json")) or []
    return W2.is_odd_case(ALL2[idx[int(m.group(1))]]) if int(m.group(1)) < len(idx) else None
for name, d, f in (("first sweep + esp-clang IR", "perfn", case_v1), ("extended sweep IR", "perfn2", case_v2)):
    t = perfn_totals(d, f)
    S[f"perfn {name}"] = t
    h(f"* {name}: {t}; functions whose asm differs without an odd-size byval aggregate: "
      f"**{t.get('asm differs WITHOUT odd byval', 0) + t.get('asm differs, function not a generated case', 0)}**; "
      f"new verifier failures: **{t.get('verifier: new failure with fix', 0)}**")
h("")

